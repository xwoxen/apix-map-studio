const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("studio", {
  chooseMap: () => ipcRenderer.invoke("map:choose"),
  openMap: (dir) => ipcRenderer.invoke("map:open", dir),
  newMap: (params) => ipcRenderer.invoke("map:new", params),
  prefabs: () => ipcRenderer.invoke("prefab:list"),
  prefab: (name) => ipcRenderer.invoke("prefab:get", name),
  savePrefab: (name, items) => ipcRenderer.invoke("prefab:save", name, items),
  deletePrefab: (name) => ipcRenderer.invoke("prefab:delete", name),
  saveMap: (dir, size, objects) => ipcRenderer.invoke("map:save", dir, size, objects),
  saveTerrain: (dir, payload) => ipcRenderer.invoke("terrain:save", dir, payload),
  terrainTextures: () => ipcRenderer.invoke("textures:list"),
  texturePreview: (game) => ipcRenderer.invoke("texture:preview", game),
  textureUrl: (game) => ipcRenderer.invoke("texture:url", game),
  exportWrite: (dir, files) => ipcRenderer.invoke("export:write", dir, files),
  environments: () => ipcRenderer.invoke("env:list"),
  environment: (name) => ipcRenderer.invoke("env:get", name),
  setEnvironment: (dir, name) => ipcRenderer.invoke("env:set", dir, name),
  library: () => ipcRenderer.invoke("library:list"),
  startupMark: (label) => ipcRenderer.invoke("startup:mark", label),
  recentObjects: () => ipcRenderer.invoke("recent:get"),
  saveRecentObjects: (list) => ipcRenderer.invoke("recent:set", list),
  catalog: (query) => ipcRenderer.invoke("catalog:query", query),
  sources: () => ipcRenderer.invoke("sources:list"),
  region: (dir, area) => ipcRenderer.invoke("region:read", dir, area),
  model: (crc) => ipcRenderer.invoke("model:get", crc),
  character: (cls) => ipcRenderer.invoke("character:get", cls),
  collisionGrid: (objects, size) => ipcRenderer.invoke("collision:grid", objects, size),
  gameSuggest: (dir, size) => ipcRenderer.invoke("game:suggest", dir, size),
  gameExport: (dir, opts) => ipcRenderer.invoke("game:export", dir, opts),
  liveList: () => ipcRenderer.invoke("live:list"),
  liveImport: (name) => ipcRenderer.invoke("live:import", name),
  liveDiff: (dir) => ipcRenderer.invoke("live:diff", dir),
  liveStage: (dir) => ipcRenderer.invoke("live:stage", dir),
  liveBaseline: (dir, baseline) => ipcRenderer.invoke("live:baseline", dir, baseline),
  snapshotSave: (dir, label) => ipcRenderer.invoke("snapshot:save", dir, label),
  snapshotList: (dir) => ipcRenderer.invoke("snapshot:list", dir),
  snapshotDiff: (dir, id) => ipcRenderer.invoke("snapshot:diff", dir, id),
  snapshotRestore: (dir, id) => ipcRenderer.invoke("snapshot:restore", dir, id),
  palettes: () => ipcRenderer.invoke("palette:get"),
  mobs: () => ipcRenderer.invoke("mobs:list"),
  mobModel: (vnum) => ipcRenderer.invoke("mob:model", vnum),
  spawns: (dir) => ipcRenderer.invoke("spawns:get", dir),
  saveSpawns: (dir, spawns, town) => ipcRenderer.invoke("spawns:save", dir, spawns, town),
  thumb: (crc) => ipcRenderer.invoke("thumb:get", crc),
  saveThumb: (crc, dataUrl) => ipcRenderer.invoke("thumb:save", crc, dataUrl),
  reveal: (file) => ipcRenderer.invoke("shell:reveal", file),
  onAutoOpen: (cb) => ipcRenderer.on("map:auto-open", (_, dir) => cb(dir)),
  readyForShot: () => ipcRenderer.send("app:ready-for-shot")
});
