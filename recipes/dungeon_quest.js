// Generates the dungeon quest and the stage regen files for apix_dungeon_01 from the arena data the map build wrote
// (<map>/_export/dungeon/arenas.json, stage*.txt). Output goes to _exports/apix_dungeon_01/server/ (staging only).
// usage: node gen_quest.js [--map 374] [--base-x <m>] [--base-y <m>] [--npc <vnum>]
//   base = the map's BasePosition / 100 (Map Studio game export prints it); without it the quest is a draft and
//   d.jump_all / new_jump use 0 + local coordinates (marked TODO in the file)
const fs = require("fs"), path = require("path");
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf("--" + k); return i >= 0 ? Number(args[i + 1]) : d; };
const MAP = opt("map", 374), BX = opt("base-x", 0), BY = opt("base-y", 0), NPC = opt("npc", 20355);
const SRC = "C:/Users/micha/Documents/we_remix_v59__20260716-1745/apix_dungeon_01/_export/dungeon";
const OUT = path.join(__dirname, "..", "server");
const data = JSON.parse(fs.readFileSync(path.join(SRC, "arenas.json"), "utf8"));
const A = Object.fromEntries(data.arenas.map((a) => [a.stage, a]));
const r = Math.round;
const draft = !BX || !BY;

const alc = (s) => A[s].alcoves.map((c) => `{${r(c.x)},${r(c.y)}}`).join(",");
const side = (s) => A[s].alcoves.filter((c) => c.a !== -90).map((c) => `{${r(c.x)},${r(c.y)}}`).join(",");
const rooms = [1, 2, 3, 4, 5].map((s) => `   if stage == ${s} then return ${BX} + ${r(A[s].entry.x)}, ${BY} + ${r(A[s].entry.y) - 4} end`).join("\n");

const quest = `-- APIX_WOLFCAVE_DUNGEON_V1 (generated by _exports/apix_dungeon_01/tools/gen_quest.js from the map build)
-- Ladova jaskyna Bieleho vlka: five stages in five variants of one arena on map ${MAP} (apix_dungeon_01).
${draft ? "-- TODO: BASE not set (--base-x / --base-y from the Map Studio game export); jumps use local coordinates only.\n" : ""}-- Entry NPC ${NPC}. Level 80+, solo or party 2-5; enemy HP scales with the party size. Limit 40 minutes.
quest apix_wolfcave begin
 state start begin
  function inside()
   return pc.get_map_index() >= ${MAP * 10000} and pc.get_map_index() < ${(MAP + 1) * 10000}
  end
  function room(stage)
${rooms}
   return ${BX} + ${r(A[1].entry.x)}, ${BY} + ${r(A[1].entry.y) - 4}
  end
  function spawn(key, race, x, y)
   local vid = d.spawn_mob(race, x, y)
   if vid == 0 then
    d.notice("Jaskyna sa zrutila. Odchod o 10 sekund.")
    d.setf("active", 0)
    server_timer("wolfcave_exit", 10, d.get_map_index())
    return false
   end
   if key != "" then d.set_unique(key, vid) d.setf("vid_"..key, vid) end
   return true
  end
  function health(key, base)
   local extra = math.max(0, math.min(4, d.getf("members") - 1))
   local hp = math.floor(base * (100 + extra * 45) / 100)
   d.unique_set_maxhp(key, hp)
   d.unique_set_hp(key, hp)
  end
  function pack(stage, races, count)
   local points = ({ [1] = {${side(1)}}, [2] = {${side(2)}}, [3] = {${alc(3)}}, [4] = {${side(4)}}, [5] = {${alc(5)}} })[stage]
   for i, p in next, points, nil do
    for k = 1, count do
     if not apix_wolfcave.spawn("", races[math.mod(i + k, table.getn(races)) + 1], p[1] + number(-3, 3), p[2] + number(-3, 3)) then return end
    end
   end
  end
  function start_stage(stage)
   d.setf("stage", stage)
   d.setf("wave", 0)
   d.kill_all()
   d.clear_regen()
   if stage > 1 then
    local x, y = apix_wolfcave.room(stage)
    d.jump_all(x, y)
   end
   if stage < 5 then d.regen_file("data/dungeon/apix_wolfcave/stage"..stage..".txt") end
   if stage == 1 then
    d.notice("LADOVA JASKYNA | I. Vstupna sien - prezite tri vlny")
   elseif stage == 2 then
    local seals = {${alc(2)}}
    for i = 1, 5 do
     if not apix_wolfcave.spawn("seal"..i, 8026, seals[i][1], seals[i][2]) then return end
     apix_wolfcave.health("seal"..i, 250000)
    end
    d.notice("II. Rozbite pecate - znicte pat pecatnych kamenov")
   elseif stage == 3 then
    if not apix_wolfcave.spawn("witch", 1191, ${r(A[3].x)}, ${r(A[3].y) + 10}) then return end
    apix_wolfcave.health("witch", 900000)
    d.notice("III. Zamrznute jazero - porazte Ladovu carodejnicu")
   elseif stage == 4 then
    local guards = {${side(4)}}
    for i = 1, 4 do
     if not apix_wolfcave.spawn("golem"..i, 1137, guards[i][1], guards[i][2]) then return end
     apix_wolfcave.health("golem"..i, 300000)
    end
    d.notice("IV. Vlci brloh - porazte styroch strazcov brlohu")
   else
    if not apix_wolfcave.spawn("queen", 1192, ${r(A[5].dais.x)}, ${r(A[5].dais.y)}) then return end
    apix_wolfcave.health("queen", 3000000)
    d.notice("V. Tron Bieleho vlka - porazte Mocnu ladovu carodejnicu")
   end
  end
  function clear_stage()
   local stage = d.getf("stage")
   d.setf("stage", stage * 10)
   if stage == 5 then
    d.setf("finished", get_global_time())
    d.notice("Biely vlk je volny. Jaskyna sa o 60 sekund uzavrie.")
    server_timer("wolfcave_exit", 60, d.get_map_index())
    return
   end
   d.notice("Cast "..stage.."/5 hotova. Pokracovanie o 10 sekund.")
   server_timer("wolfcave_next", 10, d.get_map_index())
  end
  function tick()
   local stage = d.getf("stage")
   if stage == 1 then
    if d.count_monster() == 0 then
     local wave = d.getf("wave")
     if wave >= 3 then apix_wolfcave.clear_stage() return end
     d.setf("wave", wave + 1)
     apix_wolfcave.pack(1, {1131, 1133, 1132}, 2 + wave)
     d.notice("Vlna "..(wave + 1).."/3")
    end
   elseif stage == 2 then
    local left = 0
    for i = 1, 5 do if not d.is_unique_dead("seal"..i) then left = left + 1 end end
    if left == 0 and d.count_monster() == 0 then apix_wolfcave.clear_stage() end
   elseif stage == 3 then
    if d.is_unique_dead("witch") then apix_wolfcave.clear_stage() return end
    d.setf("wave", d.getf("wave") + 1)
    if math.mod(d.getf("wave"), 15) == 0 then apix_wolfcave.pack(3, {1131, 1132}, 1) end
   elseif stage == 4 then
    local left = 0
    for i = 1, 4 do if not d.is_unique_dead("golem"..i) then left = left + 1 end end
    if left == 0 then apix_wolfcave.clear_stage() return end
    d.setf("wave", d.getf("wave") + 1)
    if math.mod(d.getf("wave"), 10) == 0 then apix_wolfcave.pack(4, {1135, 1136}, 1) end
   elseif stage == 5 then
    if d.is_unique_dead("queen") then apix_wolfcave.clear_stage() return end
    local hp = d.unique_get_hp_perc("queen")
    for i, mark in next, {75, 50, 25}, nil do
     if hp <= mark and d.getf("adds"..mark) == 0 then
      d.setf("adds"..mark, 1)
      apix_wolfcave.pack(5, {1135, 1136, 1137}, i)
      d.notice("Carodejnica vola strazcov jaskyne!")
     end
    end
   end
  end
  when ${NPC}.chat."Ladova jaskyna Bieleho vlka" with pc.get_map_index() < 10000 begin
   say_title("Ladova jaskyna Bieleho vlka")
   say("Pod Priesmykom Bieleho vlka spi ladova jaskyna.")
   say("Pat sieni, pat skusok, na konci carodejnica,")
   say("ktora drzi Bieleho vlka v ladovom spanku.")
   say("")
   say("Uroven 80+. Solo alebo skupina 2-5 hracov,")
   say("sila nepriatelov sa prisposobi. Limit 40 minut.")
   local choice = select("Vstupit solo", "Vstupit so skupinou", "Zrusit")
   if choice == 3 then return end
   if pc.get_level() < 80 and not pc.is_gm() then say("Potrebujes uroven 80.") return end
   if choice == 1 and party.is_party() then say("Pre solo vstup najprv opusti skupinu.") return end
   local members = {pc.get_player_id()}
   if choice == 2 then
    if not party.is_party() or not party.is_leader() then say("Vstup spusta vodca skupiny.") return end
    members = {party.get_member_pids()}
    if table.getn(members) < 2 or table.getn(members) > 5 or party.get_near_count() != table.getn(members) then
     say("Potrebujes 2 az 5 clenov, vsetci musia byt pri vodcovi.") return
    end
   end
   local origin = pc.get_map_index()
   local ox = pc.get_x()
   local oy = pc.get_y()
   local valid = true
   for i, pid in next, members, nil do
    q.begin_other_pc_block(pid)
    if (pc.get_level() < 80 and not pc.is_gm()) or pc.get_map_index() != origin then valid = false end
    q.end_other_pc_block()
   end
   if not valid then say("Kazdy clen musi byt na rovnakej mape a mat uroven 80.") return end
   for i, pid in next, members, nil do
    q.begin_other_pc_block(pid)
    pc.setqf("exit_map", origin)
    pc.setqf("exit_x", ox)
    pc.setqf("exit_y", oy)
    q.end_other_pc_block()
   end
   local x, y = apix_wolfcave.room(1)
   if choice == 1 then d.new_jump(${MAP}, x * 100, y * 100) else d.new_jump_party(${MAP}, x, y) end
   if not apix_wolfcave.inside_index(d.get_map_index()) then say("Vstup sa nepodaril.") return end
   d.setf("active", 1)
   d.setf("members", table.getn(members))
   d.setf("started", get_global_time())
   for i, pid in next, members, nil do d.setf("member_"..pid, 1) end
   server_timer("wolfcave_start", 6, d.get_map_index())
   server_timer("wolfcave_timeout", 2400, d.get_map_index())
  end
  function inside_index(index)
   return index >= ${MAP * 10000} and index < ${(MAP + 1) * 10000}
  end
  when wolfcave_start.server_timer begin
   if d.select(get_server_timer_arg()) and d.getf("active") == 1 and d.getf("stage") == 0 then
    apix_wolfcave.start_stage(1)
    server_timer("wolfcave_tick", 3, d.get_map_index())
   end
  end
  when wolfcave_tick.server_timer begin
   if d.select(get_server_timer_arg()) and d.getf("active") == 1 then
    apix_wolfcave.tick()
    server_timer("wolfcave_tick", 3, d.get_map_index())
   end
  end
  when wolfcave_next.server_timer begin
   if d.select(get_server_timer_arg()) and d.getf("active") == 1 then
    local stage = d.getf("stage")
    if stage >= 10 and stage < 50 then apix_wolfcave.start_stage(stage / 10 + 1) end
   end
  end
  when wolfcave_timeout.server_timer begin
   if d.select(get_server_timer_arg()) then
    d.notice("Cas vyprsal. Jaskyna vas vyhadzuje.")
    d.setf("active", 0)
    server_timer("wolfcave_exit", 10, d.get_map_index())
   end
  end
  when wolfcave_exit.server_timer begin
   if d.select(get_server_timer_arg()) then
    d.setf("active", 0)
    d.exit_all()
   end
  end
  when login with apix_wolfcave.inside() begin
   if d.getf("active") != 1 or d.getf("member_"..pc.get_player_id()) != 1 then
    pc.warp(pc.getqf("exit_x") * 100, pc.getqf("exit_y") * 100, pc.getqf("exit_map"))
    return
   end
   pc.set_warp_location(pc.getqf("exit_map"), pc.getqf("exit_x"), pc.getqf("exit_y"))
  end
  when kill with apix_wolfcave.inside() and d.getf("stage") == 2 begin
   local vid = npc.get_vid()
   for i = 1, 5 do
    if vid == d.getf("vid_seal"..i) and d.getf("seal_dead"..i) == 0 then
     d.setf("seal_dead"..i, 1)
     d.setf("seals", d.getf("seals") + 1)
     local seals = {${alc(2)}}
     for k = 1, 3 do apix_wolfcave.spawn("", 1135, seals[i][1] + number(-4, 4), seals[i][2] + number(-4, 4)) end
     d.notice("Pecate znicene: "..d.getf("seals").."/5. Ich strazcovia sa prebudili!")
    end
   end
  end
 end
end
`;
fs.mkdirSync(path.join(OUT, "quest"), { recursive: true });
fs.mkdirSync(path.join(OUT, "data", "dungeon", "apix_wolfcave"), { recursive: true });
fs.writeFileSync(path.join(OUT, "quest", "apix_wolfcave.quest"), quest.replace(/\n/g, "\n"));
for (let s = 1; s <= 5; s++) fs.copyFileSync(path.join(SRC, `stage${s}.txt`), path.join(OUT, "data", "dungeon", "apix_wolfcave", `stage${s}.txt`));
console.log((draft ? "DRAFT (no base) " : "") + "written", OUT);
